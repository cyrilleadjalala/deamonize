import { Validator } from '@seriousme/openapi-schema-validator';
import type { WorkflowSet } from '../types.js';

/**
 * Generates a valid OpenAPI 3.1 document from an annotated Workflow set.
 */
export class OpenApiGenerator {
  /**
   * Generate a valid OpenAPI 3.1 document from the annotated Workflow set.
   *
   * Throws, listing the failing paths, if the generated document does not
   * validate against the official OpenAPI 3.1 meta-schema.
   *
   * @param set - The workflow set with inputSchema/outputSchema on workflows
   * @param toolNames - Map from workflowId to snake_case tool name
   * @returns OpenAPI 3.1 document as a plain JS object
   */
  async generate(
    set: WorkflowSet,
    toolNames: Map<string, string>
  ): Promise<Record<string, unknown>> {
    const paths: Record<string, unknown> = {};

    for (const workflow of set.workflows) {
      const toolName = toolNames.get(workflow.id);
      const operationId = toolName ?? workflow.id;

      paths[`/actions/${workflow.id}`] = {
        post: {
          operationId,
          summary: workflow.label,
          tags: ['actions'],
          requestBody: {
            required: true,
            content: {
              'application/json': {
                schema: workflow.inputSchema ?? { type: 'object' },
              },
            },
          },
          responses: {
            '200': {
              description: 'Structured content of the resulting screen',
              content: {
                'application/json': {
                  schema: workflow.outputSchema ?? { type: 'object' },
                },
              },
            },
            '400': { description: 'Payload validation failure' },
            '504': { description: 'Replay timeout' },
          },
        },
      };
    }

    const doc: Record<string, unknown> = {
      openapi: '3.1.0',
      info: {
        title: set.targetName || 'Daemonize Generated API',
        version: '1',
        description:
          'Generated by Daemonize — MCP server for legacy application',
      },
      paths,
    };

    await this.validate(doc);
    return doc;
  }

  /** Validate the document against the OpenAPI 3.1 meta-schema; throws on any violation. */
  private async validate(doc: Record<string, unknown>): Promise<void> {
    const result = await new Validator().validate(doc);
    if (!result.valid) {
      const errors = (Array.isArray(result.errors) ? result.errors : [])
        .map((error) => `  - ${error.instancePath || '/'}: ${error.message}`)
        .join('\n');
      throw new Error(`OpenAPI 3.1 validation failed:\n${errors}`);
    }
  }
}
